function D = sweep_definitions()
%SWEEP_DEFINITIONS  The stress-test studies run by run_sweeps.m.
%
%   Each study changes ONE setting over a range of points, with everything
%   else at its base value. Every study uses constant east-west demand
%   (ABL_SCHED = const) for the whole 360 s run, so a point means one
%   traffic condition, not a mix of stages.
%
%   Fields
%     param   environment variable that is swept (see abl_settings.m)
%     values  points (numbers, or a cell array of names for 'driver')
%     base    other settings for this study {name, value; ...}
%     cfgs    configurations run at every point
%     ref     configurations run once per seed with the swept setting at its
%             default (point 'ref'); plotted as a dashed reference line
%     est     true = also run the estimator comparison at every point
%     xlabel  axis label;  xscale  factor applied to values for the axis
%
%   Configuration names: C1, V2V_IDM, V2V_MPC, C2, C2G, C3I, C3, C4,
%   C4_NOUNC, C4_NOONLINE, C4_SPEED, C4_STRICT, C4_SEQ, C4_NOADV, C4_ONCE, C4_NOYIELD (sim/sim_config.m)

D = struct();

D.demand = struct('param', 'ABL_DEMAND', 'values', 0.1:0.1:0.8, ...
    'base', {{'ABL_SCHED', 'const'}}, ...
    'cfgs', {{'C1', 'C2', 'C3', 'C4'}}, 'ref', {{}}, 'est', true, ...
    'xlabel', 'East-west demand [veh/s]', 'xscale', 1);

D.rtshare = struct('param', 'ABL_RT', 'values', [0.05 0.15 0.25 0.35 0.50 0.70], ...
    'base', {{'ABL_SCHED', 'const'; 'ABL_DEMAND', '0.4'}}, ...
    'cfgs', {{'C1', 'C2', 'C3', 'C4'}}, 'ref', {{}}, 'est', false, ...
    'xlabel', 'Right-turn share of arrivals [%]', 'xscale', 75);   % 0.75 x P(right | not left) x 100

D.latency = struct('param', 'ABL_LAT', 'values', [0 0.5 1 1.5 2], ...
    'base', {{'ABL_SCHED', 'const'; 'ABL_DEMAND', '0.4'}}, ...
    'cfgs', {{'C3', 'C4'}}, 'ref', {{'C1'}}, 'est', false, ...
    'xlabel', 'One-way V2X latency [s]', 'xscale', 1);

D.loss = struct('param', 'ABL_LOSS', 'values', [0 0.1 0.2 0.4 0.6], ...
    'base', {{'ABL_SCHED', 'const'; 'ABL_DEMAND', '0.4'}}, ...
    'cfgs', {{'C3', 'C4'}}, 'ref', {{'C1'}}, 'est', false, ...
    'xlabel', 'Packet loss per message [%]', 'xscale', 100);

% Human drivers have no V2X and are invisible to the RSU (ABL_SENSE = v2x).
D.penetration = struct('param', 'ABL_PEN', 'values', [0 0.25 0.5 0.75 1], ...
    'base', {{'ABL_SCHED', 'const'; 'ABL_DEMAND', '0.4'; 'ABL_SENSE', 'v2x'}}, ...
    'cfgs', {{'C2', 'C3', 'C4', 'C4_STRICT'}}, 'ref', {{'C1'}}, 'est', false, ...
    'xlabel', 'CAV penetration rate [%]', 'xscale', 100);

% How much the RSU may slow one oncoming CAV (0 = existing gaps only).
D.dmax = struct('param', 'ABL_DMAX', 'values', [0 0.5 1 2 3], ...
    'base', {{'ABL_SCHED', 'const'; 'ABL_DEMAND', '0.4'}}, ...
    'cfgs', {{'C4', 'C4_SEQ'}}, 'ref', {{'C1'}}, 'est', false, ...
    'xlabel', 'Largest delay asked of one oncoming CAV [s]', 'xscale', 1);

D.driver = struct('param', 'ABL_DRIVER', 'values', {{'aggressive', 'nominal', 'cautious'}}, ...
    'base', {{'ABL_SCHED', 'const'; 'ABL_DEMAND', '0.4'}}, ...
    'cfgs', {{'C1', 'C3', 'C4', 'C4_NOONLINE'}}, 'ref', {{}}, 'est', true, ...
    'xlabel', 'Driver population (estimators trained on nominal)', 'xscale', 1);

D.asym = struct('param', 'ABL_ASYM', 'values', [0.5 0.65 0.8], ...
    'base', {{'ABL_SCHED', 'const'; 'ABL_DEMAND', '0.5'}}, ...
    'cfgs', {{'C1', 'C3', 'C4'}}, 'ref', {{}}, 'est', false, ...
    'xlabel', 'Westbound share of east-west demand [%]', 'xscale', 100);
end
